import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { serializeRuntimeFrameContract, isRuntimeFrameContract } from './runtime-frame-contract.mjs';
import { attachTigerFrames } from '../prototype-2d/src/tiger-animation.js';
import { attachBearFrames } from '../prototype-2d/src/bear-animation.js';
import { attachBullFrames } from '../prototype-2d/src/bull-animation.js';
import { attachWolfFrames } from '../prototype-2d/src/wolf-animation.js';
import { attachMonkeyFrames } from '../prototype-2d/src/monkey-animation.js';
import { attachDeerFrames } from '../prototype-2d/src/deer-animation.js';
import { attachHawkFrames } from '../prototype-2d/src/hawk-animation.js';
import { attachSnakeFrames } from '../prototype-2d/src/snake-animation.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rows = [];
for (const [species, attach, version = 'v1'] of [['tiger', attachTigerFrames], ['bear', attachBearFrames], ['bull', attachBullFrames], ['wolf', attachWolfFrames], ['monkey', attachMonkeyFrames], ['deer', attachDeerFrames], ['hawk', attachHawkFrames], ['snake', attachSnakeFrames, 'v3']]) {
  const relative = `assets/enemy-${species}-battle-${version}-frames.json`;
  const file = path.join(root, 'prototype-2d', relative);
  const originalText = fs.readFileSync(file, 'utf8');
  const source = JSON.parse(originalText);
  const injected = structuredClone(source);
  injected.source = 'PRIVATE_PROVENANCE_SENTINEL';
  injected.prompts = ['PRIVATE_PROVENANCE_SENTINEL'];
  injected.sourceRects[0].localAccount = 'PRIVATE_PROVENANCE_SENTINEL';
  injected.states.privateNote = ['PRIVATE_PROVENANCE_SENTINEL'];
  const serialized = serializeRuntimeFrameContract(relative, JSON.stringify(injected));
  const projected = JSON.parse(serialized);
  assert.ok(isRuntimeFrameContract(relative));
  assert.ok(!serialized.includes('PRIVATE_PROVENANCE_SENTINEL'));
  assert.deepEqual(Object.keys(projected).sort(), ['size', 'referenceBodyHeight', 'previewRootXs', 'previewBaselines', 'states', 'sourceRects'].sort());
  const originalImage = attach({ width: 1774, height: 887 }, source);
  const publicImage = attach({ width: 1774, height: 887 }, projected);
  assert.deepEqual(publicImage[`__${species}Frames`], originalImage[`__${species}Frames`]);
  assert.equal(serializeRuntimeFrameContract(relative, serialized), serialized);
  projected.sourceRects[0].x = -1;
  assert.throws(() => serializeRuntimeFrameContract(relative, JSON.stringify(projected)), /Invalid/);
  assert.equal(fs.readFileSync(file, 'utf8'), originalText);
  rows.push({ species, result: 'PASS', frames: 32, checks: ['exact runtime keys', 'nested provenance excluded', 'all runtime frames unchanged', 'idempotent serialization', 'invalid crop rejected', 'repository source unchanged'] });
}
assert.equal(isRuntimeFrameContract('assets/manifest.json'), false);
assert.throws(() => serializeRuntimeFrameContract('assets/manifest.json', '{}'), /Unknown/);
const report = { generatedAt: new Date().toISOString(), result: 'PASS', scope: 'Public runtime JSON projection only; not browser or public-network acceptance', rows, unknownContractRejected: true };
fs.mkdirSync(path.join(root, 'evidence/current/bear'), { recursive: true });
fs.writeFileSync(path.join(root, 'evidence/current/bear/public-contract-node.json'), JSON.stringify(report, null, 2));
fs.mkdirSync(path.join(root, 'evidence/current/bull'), { recursive: true });
fs.writeFileSync(path.join(root, 'evidence/current/bull/public-contract-node.json'), JSON.stringify(report, null, 2));
fs.mkdirSync(path.join(root, 'evidence/current/monkey'), { recursive: true });
fs.writeFileSync(path.join(root, 'evidence/current/monkey/public-contract-node.json'), JSON.stringify(report, null, 2));
fs.mkdirSync(path.join(root, 'evidence/current/deer'), { recursive: true });
fs.writeFileSync(path.join(root, 'evidence/current/deer/public-contract-node.json'), JSON.stringify(report, null, 2));
fs.mkdirSync(path.join(root, 'evidence/current/hawk'), { recursive: true });
fs.writeFileSync(path.join(root, 'evidence/current/hawk/public-contract-node.json'), JSON.stringify(report, null, 2));
fs.mkdirSync(path.join(root, 'evidence/current/snake'), { recursive: true });
fs.writeFileSync(path.join(root, 'evidence/current/snake/public-contract-node.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
